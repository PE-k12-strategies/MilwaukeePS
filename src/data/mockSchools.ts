import type { SchoolCollection, SchoolFeature, SchoolProperties } from '../types/school'

function school(
  props: SchoolProperties,
  lng: number,
  lat: number,
): SchoolFeature {
  return {
    type: 'Feature',
    geometry: { type: 'Point', coordinates: [lng, lat] },
    properties: props,
  }
}

