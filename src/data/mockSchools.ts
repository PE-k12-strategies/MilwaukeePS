export function collectionToSchools(
  collection: SchoolCollection,
): SchoolProperties[] {
  return collection.features.map((f) => f.properties)
}

export function parseSchoolGeoJSON(data: unknown): SchoolCollection {
  if (
    typeof data !== 'object' ||
    data === null ||
    (data as SchoolCollection).type !== 'FeatureCollection' ||
    !Array.isArray((data as SchoolCollection).features)
  ) {
    throw new Error('Invalid GeoJSON: expected a FeatureCollection')
  }

  const collection = data as SchoolCollection
  for (const feature of collection.features) {
    const p = feature.properties
    if (!p?.schoolId || !p?.schoolName) {
      throw new Error(
        'Each feature must include properties.schoolId and properties.schoolName',
      )
    }
    if (typeof p.utilizationRate !== 'number') {
      throw new Error(
        `School ${p.schoolName} is missing a numeric utilizationRate`,
      )
    }
  }
  return collection
}
